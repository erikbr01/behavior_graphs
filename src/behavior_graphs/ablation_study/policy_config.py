"""Generate the rgrl data config from the study's own split.

This is the file whose staleness caused the bottles leakage. The study had a
``splits.json`` and the policy had a hand-maintained ``episode_ids`` list, they
were separate artefacts, and the second stayed frozen at an earlier 40-episode
study's 20 exclusions while the first grew to 174 with 87 held out. The policy
trained on 76 of those 87.

So the list is generated, never edited. The generated file carries the split
digest and the id digest in its header, so a config that no longer matches its
split is visible by reading it, and ``rgrl``'s own ``expected_sha256`` catches a
mismatch at load time rather than after training.
"""

from __future__ import annotations

import json
import pathlib
import textwrap

from behavior_graphs.ablation_study import splits
from behavior_graphs.ablation_study.config import DatasetConfig

#: Where rgrl looks for its data configs.
RGRL_CONFIGS = pathlib.Path("$HOME/really_good_robot_learning/configs")

CAMERAS = ("top", "left", "right")


def cache_dir(cfg: DatasetConfig) -> pathlib.Path:
    """The single zarr store under the dataset's cache root."""
    if cfg.policy_zarr is None:
        raise SystemExit(f"{cfg.name}: no policy_zarr in the config")
    orders = sorted(cfg.policy_zarr.glob("*/abc_episode_order.json"))
    if not orders:
        raise SystemExit(
            f"{cfg.name}: no abc_episode_order.json under {cfg.policy_zarr}; "
            "build the zarr cache first"
        )
    if len(orders) > 1:
        raise SystemExit(
            f"{cfg.name}: {len(orders)} zarr stores under {cfg.policy_zarr}; "
            "ambiguous which one to train on"
        )
    return orders[0].parent


def render(cfg: DatasetConfig) -> tuple[str, dict]:
    """The YAML text and the id payload it encodes."""
    store = cache_dir(cfg)
    payload = splits.rgrl_train_ids(cfg, store / "abc_episode_order.json")
    named = splits.resolve(cfg)
    order = json.loads((store / "abc_episode_order.json").read_text())

    header = textwrap.dedent(f"""\
        # GENERATED by `study policyconfig --dataset {cfg.name}`. Do not edit.
        #
        # ABC-130k `{cfg.task}`, read as a zarr store. Not the MCAP dataset
        # directly: ABC records with a 250-frame GOP, so a random seek costs
        # ~175 ms and an i.i.d. sample across three cameras ~460 ms. rgrl samples
        # randomly, so the store is materialised once, sequentially, through
        # apply_disk_cached + ResizeImages. Build it with
        #   behavior_graphs/scripts/ablation_study/build_zarr_cache.py
        #
        # 168x224 is the policy's input resolution, stored directly rather than
        # stored larger and shrunk on GPU. Letterboxed, because ABC mixes 16:9
        # and 4:3 episodes and `frame_shape` is one shape per store -- padding
        # differs between the groups rather than one being stretched relative to
        # the other, which is a cue a policy would happily learn.
        #
        # ONLY the study's train split. `episode_ids` is derived from
        # {cfg.splits_path.name} rather than maintained by hand, because the two
        # drifting apart is precisely what leaked 76 of bottles' 87 held-out
        # episodes into its policy. Regenerate, never edit.
        #
        #   split       {len(named["train"])} train / {len(named["val"])} val / {len(named["test"])} test
        #                of {sum(len(v) for v in named.values())} annotated episodes
        #   cache       {order.get("n_episodes", len(order.get("episode_dirs", [])))} episodes converted
        #   excluded    {payload["n_held_out_excluded"]} held-out episodes
        #   not cached  {payload["n_missing_from_cache"]} train episodes absent from the store
        #   split  sha  {payload["split_sha256"]}
        #   ids    sha  {payload["expected_sha256"]}
        """)

    body = {
        "name": f"abc_{cfg.name}",
        "store_path": str(store),
        "abs_action": False,
        "rename": {},
        "action_key": "action",
    }
    lines = [header]
    for k, v in body.items():
        lines.append(
            f"{k}: {json.dumps(v) if not isinstance(v, str) else v}"
            if k != "rename"
            else "rename: {}"
        )
    lines.append("")
    lines.append(f"episode_ids: {payload['episode_ids']}")
    lines.append(f"count: {payload['count']}")
    lines.append(f"expected_sha256: {payload['expected_sha256']}")
    lines.append("")
    lines.append("shape_meta:")
    lines.append("  obs:")
    for cam in CAMERAS:
        lines.append(f"    {cam}:")
        lines.append("      shape: [168, 224, 3]")
        lines.append("      type: rgb")
        lines.append("      channel_order: rgb")
    lines.append("    state:")
    lines.append("      shape: [14]")
    lines.append("      type: low_dim")
    lines.append("  action:")
    lines.append("    shape: [14]")
    return "\n".join(lines) + "\n", payload


def write(cfg: DatasetConfig, dry_run: bool = False) -> tuple[pathlib.Path, dict]:
    text, payload = render(cfg)
    dest = RGRL_CONFIGS / "data" / f"abc_{cfg.name}.yaml"
    if not dry_run:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
    return dest, payload
